_N_ELLIPSE_PARAMS = 5
_N_CIRCLE_PARAMS = 3


# --------------------------------------------------------------------------
# intervals
# --------------------------------------------------------------------------

def bca_interval(boot: np.ndarray, estimate: float, jackknife: np.ndarray,
                 alpha: float = 0.05) -> Tuple[float, float]:
    """Bias-corrected and accelerated bootstrap interval (Efron 1987).

    Falls back to the percentile interval when the correction is undefined --
    which happens when every replicate lands on one side of the estimate, or
    when the jackknife has no spread. A degenerate BCa correction would produce
    an interval that is confidently wrong, so detecting and stepping back from
    it matters more than always returning the fancier interval.
    """
    boot = np.asarray(boot, float)
    boot = boot[np.isfinite(boot)]
    if boot.size < 20:
        return (float("nan"), float("nan"))

    lo_p, hi_p = 100 * alpha / 2, 100 * (1 - alpha / 2)
    percentile = (float(np.percentile(boot, lo_p)), float(np.percentile(boot, hi_p)))

    prop = float(np.mean(boot < estimate))
    if not (0.0 < prop < 1.0):
        return percentile
    z0 = sps.norm.ppf(prop)

    jk = np.asarray(jackknife, float)
    jk = jk[np.isfinite(jk)]
    if jk.size < 3:
        return percentile
    dev = jk.mean() - jk
    denom = 6.0 * (np.sum(dev ** 2) ** 1.5)
    if denom < 1e-300:
        return percentile
    acc = float(np.sum(dev ** 3) / denom)

    out = []
    for z in (sps.norm.ppf(alpha / 2), sps.norm.ppf(1 - alpha / 2)):
        adj = z0 + (z0 + z) / (1.0 - acc * (z0 + z))
        if not np.isfinite(adj):
            return percentile
        out.append(float(np.percentile(boot, 100 * sps.norm.cdf(adj))))
    lo, hi = sorted(out)
    return (lo, hi)


def residual_bootstrap(x: np.ndarray, y: np.ndarray, ell: EllipseParams,
                       n_boot: int, rng: np.random.Generator) -> np.ndarray:
    """Bootstrap ellipse parameters by resampling orthogonal residuals.

    Residuals are inflated by sqrt(n / (n - p)) before resampling. Fitted
    residuals are systematically smaller than the true errors, because the fit
    has already absorbed p degrees of freedom; without the correction the
    intervals come out too narrow.
    """
    frame = foot_frame(ell, x, y)
    foot, normal, resid = frame["foot"], frame["normal"], frame["residual"]
    n = len(resid)
    if n <= _N_ELLIPSE_PARAMS:
        return np.zeros((0, 5))

    infl = np.sqrt(n / (n - _N_ELLIPSE_PARAMS))
    centred = (resid - resid.mean()) * infl

    draws = rng.choice(centred, size=(n_boot, n), replace=True)
    pts = foot[None, :, :] + draws[:, :, None] * normal[None, :, :]
    init = np.repeat(ell.as_array()[None, :], n_boot, axis=0)
    params, _ = fit_ellipse_batch(pts[:, :, 0], pts[:, :, 1], init)
    return params


def _jackknife_params(x: np.ndarray, y: np.ndarray, ell: EllipseParams) -> np.ndarray:
    """Leave-one-out refits, for the BCa acceleration term."""
    n = len(x)
    if n <= _N_ELLIPSE_PARAMS + 1:
        return np.zeros((0, 5))
    keep = ~np.eye(n, dtype=bool)
    xs = np.array([x[k] for k in keep])
    ys = np.array([y[k] for k in keep])
    init = np.repeat(ell.as_array()[None, :], n, axis=0)
    params, _ = fit_ellipse_batch(xs, ys, init)
    return params


def _derived(params: np.ndarray) -> Dict[str, np.ndarray]:
    """Reported quantities from a (B, 5) stack of ellipse parameters."""
    a, b = params[:, 2], params[:, 3]
    with np.errstate(divide="ignore", invalid="ignore"):
        ratio = np.where(a > 0, b / a, np.nan)
        ecc = np.sqrt(np.clip(1.0 - ratio ** 2, 0.0, 1.0))
    return {"major_axis_cm": 2 * a, "minor_axis_cm": 2 * b,
            "eccentricity": ecc, "axis_ratio": ratio}


# --------------------------------------------------------------------------
# the circularity test
# --------------------------------------------------------------------------

def circularity_test(x: np.ndarray, y: np.ndarray, ell: EllipseParams,
                     circ: CircleParams, n_boot: int,
                     rng: np.random.Generator) -> Dict[str, float]:
    """Is the ellipse a better description than a circle?

    Three views of the same comparison:

    * ``p_bootstrap`` -- the headline. Circles are simulated at this object's
      own angular sampling and residual distribution, refitted with an ellipse,
      and the observed eccentricity is placed in that null distribution. This is
      the only one of the three that is immune to short-arc inflation, because
      the null carries the same inflation.
    * ``p_f_test`` -- the classical nested F-test. Reported for readers who
      expect it, but hand-digitised points along a curve are spatially
      autocorrelated, which violates its independence assumption and makes it
      anti-conservative. It should not be led with.
    * ``delta_aicc`` / ``delta_bic`` -- information criteria, positive when the
      ellipse is preferred.
    """
    x = np.asarray(x, float)
    y = np.asarray(y, float)
    n = len(x)

    rss_e = float(np.sum(foot_frame(ell, x, y)["residual"] ** 2))
    r_circ = circle_residuals(circ, x, y)
    rss_c = float(np.sum(r_circ ** 2))

    out: Dict[str, float] = {"rss_ellipse": rss_e, "rss_circle": rss_c}

    # --- F test ---
    df_num = _N_ELLIPSE_PARAMS - _N_CIRCLE_PARAMS
    df_den = n - _N_ELLIPSE_PARAMS
    if df_den > 0 and rss_e > 0:
        f_stat = ((rss_c - rss_e) / df_num) / (rss_e / df_den)
        out["f_stat"] = float(max(f_stat, 0.0))
        out["p_f_test"] = float(sps.f.sf(max(f_stat, 0.0), df_num, df_den))
    else:
        out["f_stat"] = float("nan")
        out["p_f_test"] = float("nan")

    # --- information criteria (Gaussian least squares) ---
    def _aicc(rss: float, k_params: int) -> float:
        k = k_params + 1  # plus the variance
        if rss <= 0 or n - k - 1 <= 0:
            return float("nan")
        aic = n * np.log(rss / n) + 2 * k
        return float(aic + (2 * k * (k + 1)) / (n - k - 1))

    def _bic(rss: float, k_params: int) -> float:
        k = k_params + 1
        if rss <= 0:
            return float("nan")
        return float(n * np.log(rss / n) + k * np.log(n))

    out["delta_aicc"] = _aicc(rss_c, _N_CIRCLE_PARAMS) - _aicc(rss_e, _N_ELLIPSE_PARAMS)
    out["delta_bic"] = _bic(rss_c, _N_CIRCLE_PARAMS) - _bic(rss_e, _N_ELLIPSE_PARAMS)

    # --- parametric bootstrap under a true-circle null ---
    #
    # The null geometry is the fitted circle. Its *noise level* is the awkward
    # part, because it is a nuisance parameter and the two obvious estimates
    # disagree exactly when it matters.
    #
    # Using the circle residuals is the textbook restricted bootstrap and gives
    # essentially exact size, but on a genuinely oval object those residuals are
    # dominated by systematic lack of fit. Feeding that back in as noise widens
    # the null by as much as the signal being tested for, and power collapses.
    # Using the ellipse residuals instead fixes the power but comes out mildly
    # anti-conservative -- the wrong direction here, since a false rejection
    # means calling a circular object oval, the exact error this whole approach
    # exists to avoid.
    #
    # Measured over 300 replicates (2 se = 0.025), nominal size 0.05:
    #
    #                       size 140deg   size 180deg   power(e=.6,150deg)
    #   circle residuals       0.050         0.047            0.45
    #   ellipse residuals      0.073         0.063            1.00
    #   pooled (used here)     0.063         0.063            0.84
    #
    # So the scale is pooled across both estimates while the *shape* of the
    # residual distribution is taken from the ellipse fit, which preserves any
    # non-normality. That keeps size within Monte Carlo error of nominal and
    # recovers most of the power.
    ang = np.arctan2(y - circ.cy, x - circ.cx)
    resid_e = foot_frame(ell, x, y)["residual"]

    var_c = float(np.sum((r_circ - r_circ.mean()) ** 2) / max(n - _N_CIRCLE_PARAMS, 1))
    var_e = float(np.sum((resid_e - resid_e.mean()) ** 2) / max(n - _N_ELLIPSE_PARAMS, 1))
    sigma = np.sqrt(max(0.5 * (var_c + var_e), 0.0))

    resid_c = resid_e - resid_e.mean()
    spread = float(np.std(resid_c))
    resid_c = resid_c / spread * sigma if spread > 1e-12 else resid_c

    draws = rng.choice(resid_c, size=(n_boot, n), replace=True)
    rad = circ.r + draws
    nx = circ.cx + rad * np.cos(ang)[None, :]
    ny = circ.cy + rad * np.sin(ang)[None, :]

    # Seed each null replicate from the circle itself, very slightly
    # non-degenerate so the ellipse fit has a direction to move in.
    seed = np.tile(np.array([circ.cx, circ.cy, circ.r * 1.001, circ.r, 0.0]),
                   (n_boot, 1))
    null_params, _ = fit_ellipse_batch(nx, ny, seed)
    null_e = _derived(null_params)["eccentricity"]
    null_e = null_e[np.isfinite(null_e)]

    obs_e = ell.eccentricity
    if null_e.size >= 20:
        # The +1 keeps the p-value away from exactly zero, which is never
        # justified by a finite number of simulations.
        out["p_bootstrap"] = float((1 + np.sum(null_e >= obs_e)) / (1 + null_e.size))
        out["null_e_median"] = float(np.median(null_e))
        out["null_e_p95"] = float(np.percentile(null_e, 95))
    else:
        out["p_bootstrap"] = float("nan")
        out["null_e_median"] = float("nan")
        out["null_e_p95"] = float("nan")
    return out


