"""Uncertainty, and the circular-versus-oval decision.

The central difficulty is that eccentricity is bounded below by zero. Noise can
only push an estimate *up*, never down, so a perfect circle measured with any
error at all yields a fitted eccentricity greater than zero -- and the shorter
the surviving arc, the larger that spurious value. Reporting "e = 0.31,
therefore oval" would be measuring the digitising noise, not the object.

So the decision is made by comparing models, not by reading a number off a
fit. A five-parameter ellipse is tested against a three-parameter circle, and
the reference distribution is generated by simulating circles that carry *this
object's* arc coverage, point spacing and noise level. Whatever inflation the
short arc causes is then present in the null too, and cancels.

Intervals come from a residual bootstrap rather than resampling points. Points
are resampled in the usual bootstrap, but doing that here would randomly drop
the ends of the arc and so vary the arc coverage between replicates -- changing
the very thing that determines how well eccentricity can be estimated. Holding
the geometry fixed and resampling residuals keeps each replicate an honest
re-run of the same measurement.
"""

