@dataclass(frozen=True)
class TierThresholds:
    """Cut-offs separating reliable from marginal from indeterminate objects.

    Defaults are placeholders. ``arcfit validate`` recalibrates them from the
    simulation study, and ``arcfit truth`` checks them against the caliper
    measurements, so the published tiers are evidence-based rather than chosen.
    """

    coverage_a: float = 140.0
    coverage_b: float = 100.0
    ci_width_a: float = 0.25
    ci_width_b: float = 0.45
    rms_mm_a: float = 1.0
    rms_mm_b: float = 2.5
    extrapolation_a: float = 1.25
    extrapolation_b: float = 1.60
    size_ci_frac_a: float = 0.20
    size_ci_frac_b: float = 0.50
    calibrated_from: str = "defaults (not yet calibrated)"


DEFAULT_TIERS = TierThresholds()


def assign_tier(coverage_deg: float, ci_width_e: float, rms_mm: float,
                fit_ok: bool, rectified: bool,
                thresholds: TierThresholds = DEFAULT_TIERS,
                extrapolation: float = float("nan"),
                size_ci_frac: float = float("nan")) -> str:
    """Sort an object into tier A (reliable), B (marginal) or C (indeterminate).

    ``extrapolation`` and ``size_ci_frac`` are what catch a runaway fit. A short
    arc on a nearly circular object is badly conditioned: a fraction of a percent
    of calibration error can become several percent of size error, and
    occasionally the fit projects an outline several times larger than anything
    observed. Arc coverage alone does not catch that, because coverage is
    measured against the runaway ellipse and so looks unremarkable.
    """
    if not fit_ok:
        return "C"
    def _v(x, default=np.inf):
        return x if np.isfinite(x) else default
    ci_width_e = _v(ci_width_e)
    rms_mm = _v(rms_mm)
    extrapolation = _v(extrapolation)
    size_ci_frac = _v(size_ci_frac)

    if (rectified and coverage_deg >= thresholds.coverage_a
            and ci_width_e <= thresholds.ci_width_a and rms_mm <= thresholds.rms_mm_a
            and extrapolation <= thresholds.extrapolation_a
            and size_ci_frac <= thresholds.size_ci_frac_a):
        return "A"
    if (coverage_deg >= thresholds.coverage_b
            and ci_width_e <= thresholds.ci_width_b and rms_mm <= thresholds.rms_mm_b
            and extrapolation <= thresholds.extrapolation_b
            and size_ci_frac <= thresholds.size_ci_frac_b):
        return "B"
    return "C"


