@dataclass
class ObjectFit:
    """Everything computed for one object."""

    object_id: str = ""
    n_points: int = 0
    fit_ok: bool = False
    error: str = ""

    cx_cm: float = float("nan")
    cy_cm: float = float("nan")
    major_axis_cm: float = float("nan")
    minor_axis_cm: float = float("nan")
    eccentricity: float = float("nan")
    axis_ratio: float = float("nan")
    orientation_deg: float = float("nan")

    major_axis_lo: float = float("nan")
    major_axis_hi: float = float("nan")
    minor_axis_lo: float = float("nan")
    minor_axis_hi: float = float("nan")
    eccentricity_lo: float = float("nan")
    eccentricity_hi: float = float("nan")
    axis_ratio_lo: float = float("nan")
    axis_ratio_hi: float = float("nan")

    coverage_deg: float = float("nan")
    coverage_perimeter_frac: float = float("nan")
    extant_chord_cm: float = float("nan")
    extrapolation_factor: float = float("nan")
    size_ci_frac: float = float("nan")
    rms_residual_mm: float = float("nan")
    max_residual_mm: float = float("nan")

    circle_diameter_cm: float = float("nan")
    p_bootstrap: float = float("nan")
    p_f_test: float = float("nan")
    delta_aicc: float = float("nan")
    delta_bic: float = float("nan")
    null_e_median: float = float("nan")
    null_e_p95: float = float("nan")

    shape_class: str = "indeterminate"
    tier: str = "C"
    n_boot: int = 0
    seed: int = 0

    ellipse: Optional[EllipseParams] = None
    circle: Optional[CircleParams] = None
    boot_params: Optional[np.ndarray] = field(default=None, repr=False)

    def to_row(self) -> dict:
        """Flat dict for the results table (drops the heavy objects)."""
        d = asdict(self)
        for k in ("ellipse", "circle", "boot_params"):
            d.pop(k, None)
        return d


def classify_shape(p_bootstrap: float, ecc_hi: float, alpha: float = 0.05,
                   e_practical: float = 0.5) -> str:
    """Three-way call: elliptical, circular, or indeterminate.

    "Circular" requires more than failing to reject a circle. Failing to reject
    is not evidence of circularity when the data are too weak to have detected
    an ellipse in the first place, so it also requires the interval to *exclude*
    a practically meaningful elongation. Objects that neither reject a circle
    nor rule out a real oval are reported honestly as indeterminate rather than
    being quietly counted as round.

    ``e_practical = 0.5`` corresponds to a minor axis about 87% of the major --
    an elongation that is plainly visible rather than a statistical whisker.
    """
    if not np.isfinite(p_bootstrap):
        return "indeterminate"
    if p_bootstrap < alpha:
        return "elliptical"
    if np.isfinite(ecc_hi) and ecc_hi < e_practical:
        return "circular"
    return "indeterminate"


def analyse_points(x_cm: np.ndarray, y_cm: np.ndarray, object_id: str = "",
                   n_boot: int = 2000, seed: int = 0, alpha: float = 0.05,
                   e_practical: float = 0.5, rectified: bool = True,
                   thresholds: TierThresholds = DEFAULT_TIERS,
                   keep_boot: bool = False) -> ObjectFit:
    """Fit one object and quantify how much the answer can be trusted."""
    x = np.asarray(x_cm, float).ravel()
    y = np.asarray(y_cm, float).ravel()
    out = ObjectFit(object_id=object_id, n_points=len(x), n_boot=n_boot, seed=seed)

    if len(x) < 6:
        out.error = f"need >= 6 points, got {len(x)}"
        return out

    rng = np.random.default_rng(seed)
    try:
        ell = fit_ellipse(x, y)
        circ = fit_circle(x, y)
    except (FitError, np.linalg.LinAlgError) as exc:
        out.error = str(exc)
        return out

    if not np.all(np.isfinite(ell.as_array())) or ell.a <= 0:
        out.error = "ellipse fit did not converge to a valid ellipse"
        return out

    out.fit_ok = True
    out.ellipse, out.circle = ell, circ
    out.cx_cm, out.cy_cm = ell.cx, ell.cy
    out.major_axis_cm = ell.major_axis
    out.minor_axis_cm = ell.minor_axis
    out.eccentricity = ell.eccentricity
    out.axis_ratio = ell.b / ell.a
    out.orientation_deg = float(np.degrees(ell.theta))
    out.circle_diameter_cm = circ.diameter

    resid = foot_frame(ell, x, y)["residual"]
    out.rms_residual_mm = float(np.sqrt(np.mean(resid ** 2)) * 10.0)
    out.max_residual_mm = float(np.max(np.abs(resid)) * 10.0)

    cov = arc_coverage(ell, x, y)
    out.coverage_deg = cov["coverage_deg"]
    out.coverage_perimeter_frac = cov["coverage_perimeter_frac"]

    # The widest separation of the digitised points is a hard lower bound on the
    # reconstructed major axis, and needs no extra measurement to obtain. The
    # ratio between them says how much of the answer is extrapolation: near 1
    # the outline nearly spans the object, while a large value means the fit is
    # projecting far beyond anything actually observed, which is exactly where
    # a short-arc ellipse fit runs away.
    d2 = (x[:, None] - x[None, :]) ** 2 + (y[:, None] - y[None, :]) ** 2
    out.extant_chord_cm = float(np.sqrt(d2.max()))
    if out.extant_chord_cm > 0:
        out.extrapolation_factor = float(out.major_axis_cm / out.extant_chord_cm)

    boot = residual_bootstrap(x, y, ell, n_boot, rng)
    jack = _jackknife_params(x, y, ell)
    if boot.shape[0] >= 20:
        bd = _derived(boot)
        jd = _derived(jack) if jack.shape[0] else {k: np.zeros(0) for k in bd}
        point = {"major_axis_cm": out.major_axis_cm, "minor_axis_cm": out.minor_axis_cm,
                 "eccentricity": out.eccentricity, "axis_ratio": out.axis_ratio}
        for name, attr in (("major_axis_cm", "major_axis"), ("minor_axis_cm", "minor_axis"),
                           ("eccentricity", "eccentricity"), ("axis_ratio", "axis_ratio")):
            lo, hi = bca_interval(bd[name], point[name], jd.get(name, np.zeros(0)), alpha)
            setattr(out, f"{attr}_lo", lo)
            setattr(out, f"{attr}_hi", hi)
        if keep_boot:
            out.boot_params = boot

    test = circularity_test(x, y, ell, circ, n_boot, rng)
    for key in ("p_bootstrap", "p_f_test", "delta_aicc", "delta_bic",
                "null_e_median", "null_e_p95"):
        setattr(out, key, test.get(key, float("nan")))

    out.shape_class = classify_shape(out.p_bootstrap, out.eccentricity_hi,
                                     alpha=alpha, e_practical=e_practical)
    ci_width = out.eccentricity_hi - out.eccentricity_lo
    size_ci_frac = float("nan")
    if np.isfinite(out.major_axis_hi) and np.isfinite(out.major_axis_lo) and out.major_axis_cm > 0:
        size_ci_frac = (out.major_axis_hi - out.major_axis_lo) / out.major_axis_cm
    out.size_ci_frac = size_ci_frac
    out.tier = assign_tier(out.coverage_deg, ci_width, out.rms_residual_mm,
                           out.fit_ok, rectified, thresholds,
                           extrapolation=out.extrapolation_factor,
                           size_ci_frac=size_ci_frac)
    return out
